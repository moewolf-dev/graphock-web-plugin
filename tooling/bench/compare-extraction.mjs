#!/usr/bin/env node
/**
 * V-04: compare Readability and Defuddle on committed fixtures.
 *
 * Metrics per fixture:
 *  - coverage: extracted text length / body text length
 *  - chrome leakage: does navigation/footer text survive?
 *  - structure: heading count in the extracted HTML
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { JSDOM } from 'jsdom'
import { Readability } from '@mozilla/readability'
import { Defuddle } from 'defuddle/node'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const fixtures = join(root, 'tests/fixtures/sites')
const names = ['article.html', 'docs.html', 'forum.html']
const chromeWords = [
  'Pricing',
  'Related',
  'Copyright',
  'Trending',
  'Terms · Privacy',
  'Edit this page'
]

function normalize(text) {
  return text.replace(/\s+/gu, ' ').trim()
}

function leakage(text) {
  return chromeWords.filter((word) => text.includes(word))
}

const rows = []
for (const name of names) {
  const html = await readFile(join(fixtures, name), 'utf8')
  const baseDom = new JSDOM(html, { url: `https://example.com/${name}` })
  const bodyText = normalize(baseDom.window.document.body.textContent ?? '')

  const readabilityDom = new JSDOM(html, { url: 'https://example.com/' })
  const article = new Readability(readabilityDom.window.document).parse()
  const readabilityText = normalize(article?.textContent ?? '')

  const defuddleDom = new JSDOM(html, { url: 'https://example.com/' })
  const defuddleResult = await Defuddle(defuddleDom.window.document)
  const defuddleText = normalize(defuddleResult?.content ?? '')

  for (const candidate of [
    { engine: 'Readability', text: readabilityText, html: article?.content ?? '' },
    { engine: 'Defuddle', text: defuddleText, html: defuddleResult?.content ?? '' }
  ]) {
    rows.push({
      fixture: name,
      engine: candidate.engine,
      coverage: bodyText.length ? (candidate.text.length / bodyText.length).toFixed(2) : '0',
      chrome: leakage(candidate.text).join(', ') || 'none',
      headings: (candidate.html.match(/<h[1-3][\s>]/giu) ?? []).length
    })
  }
}

const header = '| Fixture | Engine | Text coverage | Chrome leaked | Headings |\n| --- | --- | --- | --- | --- |'
const table = rows
  .map((row) => `| ${row.fixture} | ${row.engine} | ${row.coverage} | ${row.chrome} | ${row.headings} |`)
  .join('\n')

const doc = `# Readable extraction comparison (V-04)

Generated by \`node tooling/bench/compare-extraction.mjs\` on the committed fixtures.

${header}
${table}

## Notes

- Coverage is a proxy, not a quality score: a clipper that keeps the whole page scores 1.00.
- Chrome leakage (navigation, footer, related links) is the main failure mode users notice.
- Decision: keep **Readability** as the default engine for 0.1.0 (smaller bundle, adequate
  structure on the fixtures). Revisit Defuddle when the 30-site sample set (Q-02) exists; the
  \`capture/readable\` module is the only place that needs to change.
`
await writeFile(join(root, 'docs/qa/readable-comparison.md'), doc)
console.log(table)
