#!/usr/bin/env node
/**
 * Production dependency licence gate.
 *
 * - fails on copyleft (GPL/AGPL/LGPL) and unknown licences
 * - regenerates THIRD_PARTY_NOTICES.md from the actual production tree
 */
import { execFileSync } from 'node:child_process'
import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const ALLOWED = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  '0BSD',
  'CC0-1.0',
  'Unlicense',
  'BlueOak-1.0.0',
  'Python-2.0'
])
const DENIED_PATTERN = /(^|\s)(A?GPL|LGPL|SSPL|BUSL|CC-BY-NC|UNKNOWN)(\s|$|-)/iu

function normalize(expression) {
  return String(expression ?? 'UNKNOWN')
    .replace(/[()]/gu, ' ')
    .replace(/\s+/gu, ' ')
    .trim()
}

function alternativeAllowed(expression) {
  const normalized = normalize(expression)
  if (!normalized) return false
  if (/\bOR\b/iu.test(normalized)) {
    return normalized.split(/\s+OR\s+/iu).some((part) => alternativeAllowed(part))
  }
  const parts = normalized.split(/\s+AND\s+/iu)
  return parts.every((part) => {
    const cleaned = part.replace(/^WITH\s+/iu, '').trim()
    return ALLOWED.has(cleaned)
  })
}

let json = ''
try {
  json = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024
  })
} catch (error) {
  console.error('audit-licenses: pnpm licenses failed:', error.message)
  process.exit(2)
}

const byLicense = JSON.parse(json)
const failures = []
const rows = []

for (const [license, packages] of Object.entries(byLicense)) {
  const allowed = alternativeAllowed(license)
  if (!allowed || DENIED_PATTERN.test(license)) {
    failures.push({ license, packages: packages.map((item) => item.name) })
  }
  for (const item of packages) {
    rows.push({
      name: item.name,
      version: item.versions?.join(', ') ?? '',
      license: item.license ?? license,
      homepage: item.homepage ?? ''
    })
  }
}

rows.sort((a, b) => a.name.localeCompare(b.name))
const notice = `# Third-party notices

Generated by \`pnpm lint:licenses\` from the **production** dependency tree.
Do not edit by hand.

| Package | Version | License | Homepage |
| --- | --- | --- | --- |
${rows.map((row) => `| ${row.name} | ${row.version} | ${row.license} | ${row.homepage} |`).join('\n')}
`
await writeFile(resolve(root, 'THIRD_PARTY_NOTICES.md'), notice)

if (failures.length > 0) {
  console.error('audit-licenses: disallowed or unknown licences:')
  for (const failure of failures) {
    console.error(`  ${failure.license}: ${failure.packages.join(', ')}`)
  }
  process.exit(1)
}

console.log(`audit-licenses: ${rows.length} production packages, all licences allowed`)
